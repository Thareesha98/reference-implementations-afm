import { mkdirSync, writeFileSync, rmSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "deploy");

async function loadEsbuild() {
  try {
    return await import("esbuild");
  } catch {
    const store = resolve(here, "../../node_modules/.pnpm");
    const match = existsSync(store)
      ? readdirSync(store).find((entry) => entry.startsWith("esbuild@"))
      : undefined;
    if (match === undefined) {
      throw new Error("esbuild not found - run `pnpm install` from typescript-interpreter/");
    }
    return import(pathToFileURL(join(store, match, "node_modules/esbuild/lib/main.js")).href);
  }
}

const { build } = await loadEsbuild();

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [join(here, "src/server.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: join(outDir, "server.mjs"),
  banner: { js: "// AFM MCP proxy - generated by build.mjs, do not edit by hand" },
});

writeFileSync(
  join(outDir, "package.json"),
  `${JSON.stringify(
    {
      name: "afm-mcp-proxy",
      version: "1.0.0",
      private: true,
      type: "module",
      scripts: { start: "node server.mjs" },
    },
    null,
    2,
  )}\n`,
);

console.log(`bundled -> ${join(outDir, "server.mjs")}`);
